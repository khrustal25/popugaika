const CARE_STATUS_TEXT = {
  safe: 'Допустимо при соблюдении условий',
  caution: 'Требуется дополнительная осторожность',
  unsafe: 'Небезопасно',
  unknown: 'Недостаточно проверенных данных',
}

function getCareArticle(id) {
  return CARE_ARTICLES.find((a) => a.id === id)
}

function getCareSection(id) {
  return CARE_SECTIONS.find((s) => s.id === id)
}

function searchCareWoods(query) {
  const q = String(query || '')
    .toLowerCase()
    .replaceAll('ё', 'е')
    .trim()
  if (!q) return CARE_WOODS.slice()
  return CARE_WOODS.filter((w) => {
    const hay = [w.name, ...(w.aliases || [])].join(' ').toLowerCase().replaceAll('ё', 'е')
    return hay.includes(q)
  })
}

function searchCareContent(query) {
  const q = String(query || '')
    .toLowerCase()
    .replaceAll('ё', 'е')
    .trim()
  if (!q) return []
  const out = []
  CARE_SECTIONS.forEach((s) => {
    if (
      s.title.toLowerCase().includes(q) ||
      s.description.toLowerCase().includes(q)
    ) {
      out.push({ type: 'section', id: s.id, title: s.title, href: `#/care/${s.id}` })
    }
  })
  CARE_ARTICLES.forEach((a) => {
    const blob = [
      a.title,
      a.intro,
      ...(a.subsections || []).flatMap((s) => [s.title, ...(s.content || [])]),
    ]
      .join(' ')
      .toLowerCase()
      .replaceAll('ё', 'е')
    if (blob.includes(q)) {
      out.push({ type: 'article', id: a.id, title: a.title, href: `#/care/${a.id}` })
    }
  })
  return out
}

window.CARE_SECTIONS = CARE_SECTIONS
window.CARE_ARTICLES = CARE_ARTICLES
window.CARE_WOODS = CARE_WOODS
window.CARE_STATUS_TEXT = CARE_STATUS_TEXT
window.getCareArticle = getCareArticle
window.getCareSection = getCareSection
window.searchCareWoods = searchCareWoods
window.searchCareContent = searchCareContent
