function getBehaviorTopic(id) {
  return BEHAVIOR_TOPICS.find((t) => t.id === id) || null
}

function searchBehaviorTopics(query) {
  const q = String(query || '')
    .trim()
    .toLowerCase()
  if (!q) return BEHAVIOR_TOPICS.slice()
  return BEHAVIOR_TOPICS.filter((t) => {
    const blob = [t.title, t.summary, ...(t.keywords || [])].join(' ').toLowerCase()
    return blob.includes(q) || q.split(/\s+/).some((part) => part && blob.includes(part))
  })
}

window.BEHAVIOR_TOPICS = BEHAVIOR_TOPICS
window.getBehaviorTopic = getBehaviorTopic
window.searchBehaviorTopics = searchBehaviorTopics
