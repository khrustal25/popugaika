function findDemoAnswer(question, speciesId) {
  const q = question.toLowerCase()

  const speciesSpecific = DEMO_CHAT_ANSWERS.find(
    (item) =>
      item.species?.includes(speciesId) &&
      item.keywords.some((k) => q.includes(k)),
  )
  if (speciesSpecific) return speciesSpecific

  const general = DEMO_CHAT_ANSWERS.find(
    (item) => !item.species && item.keywords.some((k) => q.includes(k)),
  )
  return general ?? null
}

window.DEMO_CHAT_ANSWERS = DEMO_CHAT_ANSWERS
window.DEMO_SUGGESTIONS = DEMO_SUGGESTIONS
window.findDemoAnswer = findDemoAnswer
