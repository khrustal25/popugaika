const HEALTH_TOPICS = HEALTH_SECTIONS.map((s) => {
  const article = HEALTH_ARTICLES[s.id]
  return {
    id: s.id,
    title: s.title,
    intro: s.description,
    urgent: s.id === 'breathing' || s.id === 'appetite' || s.id === 'symptoms',
    points: article ? article.blocks.flatMap((b) => b.items).slice(0, 6) : [s.description],
    tips: ['Смотрите подробную карточку раздела.'],
    warnings: article && article.warning ? [article.warning] : ['Информация справочная.'],
    sources: (article && article.sources) || ['Справочные материалы по здоровью птиц'],
    reviewedAt: (article && article.reviewedAt) || '2026-03-01',
  }
})

function getHealthSection(id) {
  return HEALTH_SECTIONS.find((s) => s.id === id) || null
}

function getHealthArticle(id) {
  return HEALTH_ARTICLES[id] || null
}

function getHealthSymptom(id) {
  return HEALTH_SYMPTOMS.find((s) => s.id === id) || null
}

function getHealthSafety(id) {
  return HEALTH_SAFETY.find((s) => s.id === id) || null
}

