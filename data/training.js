function getTrainingLesson(id) {
  return TRAINING_LESSONS.find((l) => l.id === id) || null
}

function getTrainingMistake(id) {
  return TRAINING_MISTAKES.find((m) => m.id === id) || null
}

function getTrainingBody(id) {
  return TRAINING_BODY_LANGUAGE.find((b) => b.id === id) || null
}

