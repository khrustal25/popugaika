function getFoodById(id) {
  return FOODS.find((f) => f.id === id)
}

function getFoodsByCategory(category) {
  return FOODS.filter((f) => f.category === category)
}

function normalizeSearch(text) {
  return String(text || '')
    .toLowerCase()
    .replaceAll('ё', 'е')
    .trim()
}

function searchFoods(query) {
  const q = normalizeSearch(query)
  if (!q) return []
  return FOODS.filter((f) => {
    const hay = [f.name, ...(f.aliases || [])].map(normalizeSearch).join(' ')
    return hay.includes(q) || normalizeSearch(f.name).startsWith(q)
  })
}

function getSpeciesFoodStatus(food, speciesId) {
  if (!speciesId) return food.safetyStatus
  return food.suitableSpecies[speciesId] || food.safetyStatus
}

function filterFoods({ category = null, status = null, query = '', speciesId = null } = {}) {
  let list = FOODS.slice()
  if (category) list = list.filter((f) => f.category === category)
  const q = normalizeSearch(query)
  if (q) {
    list = list.filter((f) => {
      const hay = [f.name, ...(f.aliases || [])].map(normalizeSearch).join(' ')
      return hay.includes(q)
    })
  }
  if (status) {
    list = list.filter((f) => getSpeciesFoodStatus(f, speciesId) === status)
  }
  return list
}

